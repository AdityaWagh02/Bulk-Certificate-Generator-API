"""Business logic: create jobs and process them.

Processing model
----------------
POST /api/jobs only validates the request and stores the recipients, then it
returns 202 immediately. The actual PDF generation runs in a background
thread pool. The client polls GET /api/jobs/<id> to see the progress.
Reason: generating 1000 PDFs takes a while and we do not want the HTTP
request to time out.
"""
import logging
import os
import uuid
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime, timezone

from . import certificate
from .db import get_conn
from .validators import validate_recipient

log = logging.getLogger(__name__)

# job statuses
PENDING = "PENDING"
PROCESSING = "PROCESSING"
COMPLETED = "COMPLETED"
COMPLETED_WITH_ERRORS = "COMPLETED_WITH_ERRORS"
FAILED = "FAILED"  # every certificate failed

# certificate statuses
CERT_PENDING = "PENDING"
CERT_SUCCESS = "SUCCESS"
CERT_FAILED = "FAILED"


def _now():
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def create_job(db_path, payload):
    """Validate every recipient and store the job.

    Invalid recipients are stored as FAILED right away (with the reason),
    valid ones are stored as PENDING and will be generated by the worker.
    Returns the job id.
    """
    job_id = uuid.uuid4().hex
    now = _now()
    recipients = payload["recipients"]
    seen_emails = set()

    rows = []
    invalid_count = 0
    for position, recipient in enumerate(recipients):
        cleaned, error = validate_recipient(recipient, seen_emails)
        if error:
            invalid_count += 1
        rows.append((
            uuid.uuid4().hex, job_id, position,
            cleaned["name"], cleaned["email"], cleaned["course"],
            CERT_FAILED if error else CERT_PENDING,
            error, None, now,
        ))

    # if nothing is valid there is nothing to process
    status = FAILED if invalid_count == len(recipients) else PENDING
    completed_at = now if status == FAILED else None

    with get_conn(db_path) as conn:
        conn.execute(
            "INSERT INTO jobs (id, event_name, issued_by, issue_date, status, total, created_at, completed_at) "
            "VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
            (job_id, payload["event_name"], payload["issued_by"], payload["issue_date"],
             status, len(recipients), now, completed_at),
        )
        conn.executemany(
            "INSERT INTO certificates (id, job_id, position, name, email, course, status, error, file_path, created_at) "
            "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
            rows,
        )
    return job_id, status


def process_job(db_path, certificate_dir, job_id):
    """Generate all PENDING certificates of a job.

    Every certificate is wrapped in its own try/except so one failure does
    not stop the others. Each result is committed immediately, which is what
    makes the progress endpoint show live numbers.
    """
    try:
        with get_conn(db_path) as conn:
            job = conn.execute("SELECT * FROM jobs WHERE id = ?", (job_id,)).fetchone()
            if job is None:
                return
            conn.execute("UPDATE jobs SET status = ? WHERE id = ?", (PROCESSING, job_id))
            pending = conn.execute(
                "SELECT id, name, course FROM certificates "
                "WHERE job_id = ? AND status = ? ORDER BY position",
                (job_id, CERT_PENDING),
            ).fetchall()

        job_dir = os.path.join(certificate_dir, job_id)

        for cert in pending:
            file_path = os.path.join(job_dir, f"{cert['id']}.pdf")
            try:
                certificate.generate_certificate(
                    file_path,
                    name=cert["name"],
                    event_name=job["event_name"],
                    issued_by=job["issued_by"],
                    issue_date=job["issue_date"],
                    course=cert["course"],
                )
                new_status, error, stored_path = CERT_SUCCESS, None, file_path
            except Exception as exc:  # noqa: BLE001 - we really want to catch everything here
                log.warning("Certificate %s failed: %s", cert["id"], exc)
                new_status, error, stored_path = CERT_FAILED, f"Generation failed: {exc}", None

            with get_conn(db_path) as conn:
                conn.execute(
                    "UPDATE certificates SET status = ?, error = ?, file_path = ? WHERE id = ?",
                    (new_status, error, stored_path, cert["id"]),
                )
    except Exception:  # something unexpected for the whole job
        log.exception("Job %s crashed", job_id)
        with get_conn(db_path) as conn:
            conn.execute(
                "UPDATE jobs SET status = ?, completed_at = ? WHERE id = ?",
                (FAILED, _now(), job_id),
            )
        return

    _finish_job(db_path, job_id)


def _finish_job(db_path, job_id):
    with get_conn(db_path) as conn:
        counts = _count_by_status(conn, job_id)
        if counts[CERT_FAILED] == 0:
            final = COMPLETED
        elif counts[CERT_SUCCESS] == 0:
            final = FAILED
        else:
            final = COMPLETED_WITH_ERRORS
        conn.execute(
            "UPDATE jobs SET status = ?, completed_at = ? WHERE id = ?",
            (final, _now(), job_id),
        )


def _count_by_status(conn, job_id):
    counts = {CERT_PENDING: 0, CERT_SUCCESS: 0, CERT_FAILED: 0}
    rows = conn.execute(
        "SELECT status, COUNT(*) AS n FROM certificates WHERE job_id = ? GROUP BY status",
        (job_id,),
    ).fetchall()
    for row in rows:
        counts[row["status"]] = row["n"]
    return counts


def get_job_status(db_path, job_id):
    """Return a dict describing the job and its progress, or None."""
    with get_conn(db_path) as conn:
        job = conn.execute("SELECT * FROM jobs WHERE id = ?", (job_id,)).fetchone()
        if job is None:
            return None
        counts = _count_by_status(conn, job_id)

    total = job["total"]
    processed = counts[CERT_SUCCESS] + counts[CERT_FAILED]
    return {
        "job_id": job["id"],
        "status": job["status"],
        "event_name": job["event_name"],
        "issued_by": job["issued_by"],
        "issue_date": job["issue_date"],
        "total": total,
        "successful": counts[CERT_SUCCESS],
        "failed": counts[CERT_FAILED],
        "pending": counts[CERT_PENDING],
        "progress_percent": round(processed * 100 / total, 1) if total else 100.0,
        "created_at": job["created_at"],
        "completed_at": job["completed_at"],
    }


def list_certificates(db_path, job_id, status=None):
    """Return list of certificates of a job (or None if the job does not exist)."""
    with get_conn(db_path) as conn:
        job = conn.execute("SELECT id FROM jobs WHERE id = ?", (job_id,)).fetchone()
        if job is None:
            return None
        query = "SELECT * FROM certificates WHERE job_id = ?"
        params = [job_id]
        if status:
            query += " AND status = ?"
            params.append(status)
        query += " ORDER BY position"
        rows = conn.execute(query, params).fetchall()
    return [dict(r) for r in rows]


def get_certificate(db_path, certificate_id):
    with get_conn(db_path) as conn:
        row = conn.execute("SELECT * FROM certificates WHERE id = ?", (certificate_id,)).fetchone()
    return dict(row) if row else None


class JobRunner:
    """Runs jobs either in a thread pool (normal) or inline (tests)."""

    def __init__(self, db_path, certificate_dir, workers=2, sync=False):
        self.db_path = db_path
        self.certificate_dir = certificate_dir
        self.sync = sync
        self.executor = None if sync else ThreadPoolExecutor(max_workers=workers, thread_name_prefix="certgen")

    def submit(self, job_id):
        if self.sync:
            process_job(self.db_path, self.certificate_dir, job_id)
        else:
            self.executor.submit(process_job, self.db_path, self.certificate_dir, job_id)
